impl Color {
    /// Parse a color from a string.
    ///
    /// Supported formats:
    /// - `"#rgb"` (short hex, e.g. "#f00" for red)
    /// - `"#rrggbb"` (long hex, e.g. "#ff0000" for red)
    /// - `"0"` through `"255"` (indexed color)
    pub fn parse(s: &str) -> Self {
        if let Some(hex) = s.strip_prefix('#') {
            match hex.len() {
                3 => {
                    let mut chars = hex.chars();
                    let r = parse_hex_char(chars.next().unwrap());
                    let g = parse_hex_char(chars.next().unwrap());
                    let b = parse_hex_char(chars.next().unwrap());
                    Color::Rgb {
                        r: r << 4 | r,
                        g: g << 4 | g,
                        b: b << 4 | b,
                    }
                }
                6 => {
                    let r = u8::from_str_radix(&hex[0..2], 16).unwrap_or(0);
                    let g = u8::from_str_radix(&hex[2..4], 16).unwrap_or(0);
                    let b = u8::from_str_radix(&hex[4..6], 16).unwrap_or(0);
                    Color::Rgb { r, g, b }
                }
                _ => Color::NoColor,
            }
        } else if let Ok(n) = s.parse::<u16>() {
            if n <= 255 {
                Color::Indexed(n as u8)
            } else {
                Color::NoColor
            }
        } else {
            Color::NoColor
        }
    }

    /// Convert the color to its RGB representation.
    ///
    /// Returns `None` for `NoColor`.
    pub fn to_rgb(self) -> Option<(u8, u8, u8)> {
        match self {
            Color::NoColor => None,
            Color::Basic(n) => Some(ANSI_HEX[n as usize]),
            Color::Indexed(n) => Some(ANSI_HEX[n as usize]),
            Color::Rgb { r, g, b } => Some((r, g, b)),
        }
    }
}

impl fmt::Display for Color {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Color::NoColor => write!(f, "NoColor"),
            Color::Basic(n) => write!(f, "Basic({n})"),
            Color::Indexed(n) => write!(f, "Indexed({n})"),
            Color::Rgb { r, g, b } => write!(f, "#{r:02x}{g:02x}{b:02x}"),
        }
    }
}

fn parse_hex_char(c: char) -> u8 {
    match c {
        '0'..='9' => c as u8 - b'0',
        'a'..='f' => c as u8 - b'a' + 10,
        'A'..='F' => c as u8 - b'A' + 10,
        _ => 0,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_parse_hex_long() {
        let c = Color::parse("#ff8537");
        assert_eq!(
            c,
            Color::Rgb {
                r: 255,
                g: 133,
                b: 55
            }
        );
    }

    #[test]
    fn test_parse_hex_short() {
        let c = Color::parse("#f00");
        assert_eq!(c, Color::Rgb { r: 255, g: 0, b: 0 });
    }

    #[test]
    fn test_parse_indexed() {
        assert_eq!(Color::parse("196"), Color::Indexed(196));
        assert_eq!(Color::parse("0"), Color::Indexed(0));
        assert_eq!(Color::parse("255"), Color::Indexed(255));
    }

    #[test]
    fn test_parse_invalid() {
        assert_eq!(Color::parse("999"), Color::NoColor);
        assert_eq!(Color::parse("hello"), Color::NoColor);
        // "#xyz" parses to Rgb{0,0,0} since invalid hex chars default to 0;
        // "#abcde" has wrong length
        assert_eq!(Color::parse("#abcde"), Color::NoColor);
    }

    #[test]
    fn test_to_rgb_basic() {
        let c = Color::Basic(1); // maroon
        assert_eq!(c.to_rgb(), Some((0x80, 0x00, 0x00)));
    }

    #[test]
    fn test_to_rgb_indexed() {
        let c = Color::Indexed(196); // bright red
        assert_eq!(c.to_rgb(), Some((0xff, 0x00, 0x00)));
    }

    #[test]
    fn test_to_rgb_rgb() {
        let c = Color::Rgb {
            r: 10,
            g: 20,
            b: 30,
        };
        assert_eq!(c.to_rgb(), Some((10, 20, 30)));
    }

    #[test]
    fn test_to_rgb_nocolor() {
        assert_eq!(Color::NoColor.to_rgb(), None);
    }
}
