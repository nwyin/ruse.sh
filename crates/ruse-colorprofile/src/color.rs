use std::fmt;

/// A color that can represent NoColor, a basic ANSI color (0-15),
/// an indexed 256-color palette entry, or a 24-bit RGB color.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Color {
    /// No color / transparent.
    NoColor,
    /// Basic ANSI color (0-15, 4-bit).
    Basic(u8),
    /// Indexed color (0-255, 8-bit). Indices 0-15 overlap with Basic.
    Indexed(u8),
    /// 24-bit RGB color.
    Rgb { r: u8, g: u8, b: u8 },
}

